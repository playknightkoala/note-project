const { chromium } = await import(process.env.NOTES_PLAYWRIGHT_MODULE ?? 'playwright');
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
// 僅對一次性測試容器執行；會建立隨機合成帳號與筆記。
const origin = new URL(process.argv[2] ?? 'http://127.0.0.1:18082').origin;
const browser = await chromium.launch({ ...(process.env.NOTES_CHROME_PATH ? { executablePath: process.env.NOTES_CHROME_PATH } : {}), headless: true });
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const credentials = '/tmp/notes-sidebar-smoke-credentials.json';
  const account = existsSync(credentials) ? JSON.parse(readFileSync(credentials, 'utf8')) : { email: `${randomUUID()}@example.test`, displayName: '側欄選單驗收', password: randomUUID() };
  writeFileSync(credentials, JSON.stringify(account), { mode: 0o600 });
  const setup = await (await context.request.get(origin + '/api/auth/status')).json();
  const auth = await context.request.post(origin + (setup.setupRequired ? '/api/auth/register' : '/api/auth/login'), { headers: { origin }, data: setup.setupRequired ? account : { identifier: account.email, password: account.password } });
  assert.ok(auth.ok());
  const session = await auth.json();
  const created = await context.request.post(origin + '/api/pages', { headers: { origin, 'x-csrf-token': session.csrfToken }, data: { title: '選單滑鼠移動驗收' } });
  const note = await created.json();
  const page = await context.newPage();
  await page.goto(origin + '/p/' + note.page.id);
  const row = page.locator(`.page-tree .tree-row[data-id="${note.page.id}"]`).last();
  await row.hover();
  await row.getByRole('button', { name: '頁面選項', exact: true }).click();
  const menu = page.getByRole('menu', { name: '頁面選項', exact: true });
  const item = menu.getByRole('menuitem', { name: '加入最愛', exact: true });
  await item.waitFor({ state: 'visible' });
  const bounds = await item.boundingBox();
  await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2, { steps: 12 });
  await page.waitForTimeout(350);
  assert.ok(await item.isVisible(), '滑鼠從「…」移入選單後，選單必須保持開啟');
  await Promise.all([page.waitForResponse(response => response.url() === origin + `/api/pages/${note.page.id}/favorite` && response.status() === 200), item.click()]);
  const tree = await (await context.request.get(origin + '/api/pages/tree')).json();
  assert.equal(tree.pages.find(p => p.id === note.page.id).isFavorite, true);
  await menu.waitFor({ state: 'hidden' });
  await row.click({ button: 'right' });
  const rightItem = page.getByRole('menu', { name: '側欄頁面右鍵選單', exact: true }).getByRole('menuitem', { name: '移除最愛', exact: true });
  await rightItem.waitFor({ state: 'visible' });
  await rightItem.hover();
  assert.ok(await rightItem.isVisible(), '右鍵選單仍應正常');
  await page.keyboard.press('Escape');
  await rightItem.waitFor({ state: 'hidden' });
  await row.hover();
  const trigger = row.getByRole('button', { name: '頁面選項', exact: true });
  await trigger.focus(); await page.keyboard.press('Enter');
  const reopened = menu.getByRole('menuitem', { name: '移除最愛', exact: true });
  await reopened.waitFor({ state: 'visible' });
  await page.getByRole('textbox', { name: '頁面標題', exact: true }).click();
  await reopened.waitFor({ state: 'hidden' });
  console.log('PASS 桌面「…」移入選單、選單操作、右鍵、Escape、鍵盤開啟與點外關閉');
  await context.close();
} finally { await browser.close(); }
